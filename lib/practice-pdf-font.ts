/**
 * Font metadata and glyph set of the printable practice worksheet PDF.
 *
 * The PDF is rendered in the browser by react-pdf, which embeds a *subset* of
 * the registered font into the file. That subsetter only works on TrueType
 * sources: with a WOFF2 font it writes the composite glyphs out of bounds
 * ("RangeError: Offset is outside the bounds of the DataView"), so the PDF
 * path needs a TTF.
 *
 * Shipping the full 6.3 MB ZCOOL XiaoWei TTF for that would cost a 6.3 MB
 * download for a single blank worksheet, so the PDF gets its own TTF subset
 * that holds exactly the characters the PDF draws. The file is generated by
 * scripts/fonts/subset-brush-fonts.mjs.
 *
 * This module is imported both by the client component that renders the PDF
 * and by the build script that generates the font, so it must stay free of
 * imports (no server-only code, no path aliases).
 */

/** Font family registered with react-pdf for the practice PDF. */
export const PRACTICE_PDF_FONT_FAMILY = 'ZCOOLXiaoWei';

/** File name of the PDF font subset under public/fonts/. */
export const PRACTICE_PDF_FONT_FILE = 'zcool-xiaowei-pdf.ttf';

/** URL of the PDF font subset, as registered with react-pdf. */
export const PRACTICE_PDF_FONT_URL = `/fonts/${PRACTICE_PDF_FONT_FILE}`;

/** Brand line of the PDF header. */
export const PRACTICE_PDF_BRAND = '字·韵';

/** Subtitle of the PDF header. */
export const PRACTICE_PDF_SUBTITLE = '空白字帖 · 公益网站，多多支持';

/**
 * Every cell-style label the PDF header can show.
 *
 * Mirrors cellStyleLabel() in lib/worksheet-types.ts: the tool (钢笔 / 毛笔)
 * combined with the presentation (田字格 / 米字格 / 横线 / 英文描红) and the
 * optional 描红 suffix. The unit test pins this list against cellStyleLabel()
 * so the two cannot drift apart.
 */
export const PRACTICE_PDF_CELL_STYLE_LABELS: readonly string[] = [
  '钢笔·田字格',
  '钢笔·米字格',
  '钢笔·田字格·描红',
  '钢笔·米字格·描红',
  '钢笔·横线',
  '钢笔·英文描红',
  '毛笔·田字格',
  '毛笔·米字格',
  '毛笔·田字格·描红',
  '毛笔·米字格·描红',
  '毛笔·横线',
  '毛笔·英文描红',
];

/** Printable ASCII — the site host in the PDF footer is a domain name. */
function printableAscii(): string {
  let out = '';
  for (let code = 0x20; code <= 0x7e; code += 1) {
    out += String.fromCharCode(code);
  }
  return out;
}

/**
 * Characters the PDF font subset has to contain: the printable ASCII plus
 * every character of the brand, the subtitle and the cell-style labels.
 *
 * The result is deduplicated and ordered deterministically, so the generated
 * font file only changes when the PDF text changes.
 */
export function practicePdfFontCharset(): string {
  const text = [
    PRACTICE_PDF_BRAND,
    PRACTICE_PDF_SUBTITLE,
    ...PRACTICE_PDF_CELL_STYLE_LABELS,
  ].join('');
  const chars = new Set<string>([...printableAscii(), ...text]);
  return [...chars].join('');
}
